/**
 * Build the server-side Lucide icon map used by <x-icon>.
 *
 * The reference bundle uses inline SVG icons. Production renders icons on the
 * server so Livewire morphing can never drop them. This script scans Blade
 * files and emits only the icons that are actually referenced.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { icons } from 'lucide';

const root = fileURLToPath(new URL('..', import.meta.url));
const viewsDir = join(root, 'resources', 'views');
const outFile = join(root, 'resources', 'lucide-icons.php');

const pascalToKebab = (value) =>
    value
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
        .replace(/([a-zA-Z])([0-9])/g, '$1-$2')
        .toLowerCase();

const kebabToPascal = (value) =>
    value
        .split('-')
        .filter(Boolean)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');

const iconMap = new Map();
for (const [name, data] of Object.entries(icons)) {
    iconMap.set(pascalToKebab(name), data);
}

const escapeAttribute = (value) =>
    String(value)
        .replaceAll('&', '&amp;')
        .replaceAll('"', '&quot;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;');

const serializeNode = ([tag, attrs]) => {
    const attributes = Object.entries(attrs ?? {})
        .map(([key, value]) => `${key}="${escapeAttribute(value)}"`)
        .join(' ');

    return `<${tag}${attributes ? ` ${attributes}` : ''}/>`;
};

const serializeIcon = (data) => data.map(serializeNode).join('');

const walk = async (directory) => {
    const entries = await readdir(directory, { withFileTypes: true });
    const files = [];

    for (const entry of entries) {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) {
            files.push(...(await walk(path)));
        } else if (entry.name.endsWith('.blade.php')) {
            files.push(path);
        }
    }

    return files;
};

const files = await walk(viewsDir);
const used = new Set([
    // Icons chosen dynamically in Blade. Keep this list in sync when adding
    // status-dependent icon expressions.
    'check',
    'eye',
    'pencil',
    'plus',
    'receipt',
    'user-check',
    'user-x',
    // Navigation items are supplied as data by App\Support\Navigation, so the
    // static scan below cannot see their icon names.
    'layout-dashboard',
    'shield-check',
    'repeat',
    'users',
    'qr-code',
    'graduation-cap',
    'school',
    'calendar-days',
    'user-plus',
    'clipboard-check',
    'award',
    'file-text',
    'pen-line',
    'medal',
    'heart-handshake',
    'shield-alert',
    'users-round',
    'briefcase',
    'clipboard-list',
    'wallet',
    'package',
    'library',
    'heart-pulse',
    'bus',
    'store',
    'send',
    'megaphone',
    'bar-chart-3',
    'settings',
    'user-cog',
    'shield',
    'credit-card',
    'circle-help',
    'puzzle',
    'scroll-text',
    'user-round-check',
    'contact-round',
    'zap',
    'panel-left-open',
    'panel-left-close',
    'chevrons-up-down',
    'sparkles',
    'arrow-up-right',
    'log-out',
    'menu',
    'search',
    'sun',
    'moon',
    'bell',
    'chevron-right',
    'chevron-down',
    'corner-down-left',
    'edit-3',
    'clock',
    'check-circle',
    'alert-triangle',
    'eye-off',
    'lock',
]);

for (const file of files) {
    const source = await readFile(file, 'utf8');

    for (const match of source.matchAll(/<x-icon\b[^>]*\bname="([^"]+)"/g)) {
        used.add(match[1]);
    }

    for (const match of source.matchAll(/data-lucide="([^"]+)"/g)) {
        used.add(match[1]);
    }
}

const map = {};
const missing = [];

for (const name of [...used].sort()) {
    const data = iconMap.get(name);

    if (!data) {
        missing.push(name);
        continue;
    }

    map[name] = serializeIcon(data);
}

// Emit Pint-style single-quoted strings, not JSON double quotes: the
// committed file is Pint-formatted, so regenerating from a clean tree must
// be a no-op. Escape backslashes and single quotes; SVG payloads only ever
// contain double quotes, which are literal inside single quotes.
const phpString = (value) =>
    `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

const entries = Object.entries(map)
    .map(([name, svg]) => `    ${phpString(name)} => ${phpString(svg)},`)
    .join('\n');
const php = `<?php\n\n// Generated by \`npm run icons\`. Do not edit manually.\n\nreturn [\n${entries}\n];\n`;

await writeFile(outFile, php, 'utf8');

console.log(`Generated ${Object.keys(map).length} icons from ${files.length} Blade files.`);
if (missing.length > 0) {
    console.warn(`Missing icons: ${missing.join(', ')}`);
}
